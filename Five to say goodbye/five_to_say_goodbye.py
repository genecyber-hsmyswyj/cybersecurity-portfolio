def verse_1():
    print("\n=== Verse 1 ===")
    print("First one grabbed onto my lace,")
    print("Held me tight, but lost the chase.")
    print("Pulled my leg, his last embrace,")
    print("Now he's just a breeze, erased.")

def pre_chorus():
    print("\n=== Pre-Chorus ===")
    print("One by one, they slip away,")
    print("Not my fault, just luck that strayed.")
    print("Now the radio sings their fate…")

def chorus():
    print("\n=== Chorus ===")
    print("Boom, boom, the bomb went high,")
    print("Tick, tock, five to say goodbye.")
    print("One by one, they’re out of time,")
    print("Now they live inside my rhyme.")

def verse_2():
    print("\n=== Verse 2 ===")
    print("Number two thought life's a dream,")
    print("Said goodbye so carelessly.")
    print("But the spark had other plans,")
    print("Now he's fire in the breeze.")

def bridge():
    print("\n=== Bridge ===")
    print("Down below, the night was cold,")
    print("A hose, a door, a fate untold.")
    print("Should’ve left, should’ve known,")
    print("But time was cruel, and now he's gone.")

def final_chorus():
    print("\n=== Final Chorus ===")
    print("Boom, boom, the bomb went high,")
    print("Tick, tock, five to say goodbye.")
    print("One by one, they’re out of time,")
    print("Now they live inside my rhyme…")

# ==========================================
#            Ejecutar la canción
# ==========================================

def cantar():
    verse_1()
    pre_chorus()
    chorus()
    verse_2()
    pre_chorus()
    chorus()
    bridge()
    final_chorus()

# ==========================================
#             Let it sing...
# ==========================================

if __name__ == "__main__":
    cantar()
